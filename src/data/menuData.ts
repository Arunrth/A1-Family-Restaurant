/**
 * Helper to resolve appropriate culinary image for any dish
 */
export function getDishImage(dish: Partial<MenuItem>): string {
  if (dish.image) return dish.image;
  const name = (dish.name || '').toLowerCase();
  const category = dish.category || '';

  // 1. Breads & Roti
  if (category === 'breads' || name.includes('roti') || name.includes('naan') || name.includes('kulcha') || name.includes('paratha')) {
    return '/images/menu-breads.jpg';
  }
  // 2. Egg Dishes
  if (dish.dietType === 'egg' || name.includes('egg') || (name.includes('bhurji') && !name.includes('paneer')) || name.includes('omelet') || name.includes('omlet') || name.includes('half fry') || name.includes('boiled')) {
    return '/images/menu-egg.jpg';
  }
  // 3. Dal & Lentils
  if (name.includes('dal') || name.includes('tadka') || (name.includes('makhani') && !name.includes('murgh') && !name.includes('chicken'))) {
    return '/images/menu-dal.jpg';
  }
  // 4. Paneer Main Courses & Starters
  if (name.includes('paneer')) {
    if (category === 'starters' || name.includes('chilli') || name.includes('chilly') || name.includes('crispy')) {
      return '/images/menu-starters.jpg';
    }
    return '/images/menu-paneer.jpg';
  }
  // 5. Chicken Dishes
  if (name.includes('chicken') || name.includes('murgh')) {
    if (name.includes('biryani')) return '/images/gallery-biryani.jpg';
    if (name.includes('noodles') || name.includes('fried rice') || (name.includes('rice') && category === 'rice-noodles')) return '/images/menu-noodles.jpg';
    if (name.includes('tandoori') || name.includes('tikka') || name.includes('kabab') || name.includes('kebab') || name.includes('roast')) return '/images/gallery-tandoori.jpg';
    if (category === 'starters' || name.includes('chilli') || name.includes('chilly') || name.includes('65') || name.includes('manchurian') || name.includes('crispy')) return '/images/menu-starters.jpg';
    return '/images/menu-chicken.jpg';
  }
  // 6. Biryani & Rice
  if (category === 'rice-biryani' || name.includes('biryani') || name.includes('pulao') || name.includes('jeera rice') || name.includes('steamed rice') || name.includes('rice bowl')) {
    return '/images/gallery-biryani.jpg';
  }
  // 7. Noodles & Fried Rice
  if (category === 'rice-noodles' || name.includes('noodle') || name.includes('chowmein') || name.includes('fried rice') || name.includes('schezwan rice') || name.includes('tripple') || name.includes('triple')) {
    return '/images/menu-noodles.jpg';
  }
  // 8. Indo-Chinese Starters / Manchurian / Chilli
  if (category === 'starters' || name.includes('manchurian') || name.includes('chilli') || name.includes('chilly') || name.includes('crispy') || name.includes('65') || name.includes('corn')) {
    if (name.includes('tikka') || name.includes('kabab') || name.includes('tandoori')) return '/images/gallery-tandoori.jpg';
    return '/images/menu-starters.jpg';
  }
  // 9. Snacks & Street food
  if (category === 'snacks' || name.includes('chole') || name.includes('bhature') || name.includes('roll') || name.includes('french fries') || name.includes('cutlet') || name.includes('sandwich') || name.includes('pakora')) {
    return '/images/hero-spread.jpg';
  }
  // 10. Soups & Salads & Accompaniments
  if (category === 'soups-salads' || name.includes('soup') || name.includes('salad') || name.includes('raita') || name.includes('papad')) {
    return '/images/about-ambience.jpg';
  }
  // 11. Pizza & Pasta
  if (category === 'pizza-pasta' || name.includes('pizza') || name.includes('pasta') || name.includes('maggi') || name.includes('macaroni')) {
    return '/images/menu-noodles.jpg';
  }
  // 12. Main course curries (Mushroom, Mix Veg, Kofta, Kaju, etc.)
  if (category === 'mains') {
    return '/images/gallery-curry.jpg';
  }
  return '/images/hero-spread.jpg';
}
